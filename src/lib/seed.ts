function centreIdFor(patientId: string) {
  return patients.find((patient) => patient.id === patientId)?.centreId ?? ""
}

export function createSeed(): Database {
  const sessions: DialysisSession[] = sessionSeeds.map((seed) => {
    const [patientId, sessionDate, arrival, post, dry, duration, systolic, diastolic, notes] =
      seed
    return {
      id: `ses-${patientId}-${sessionDate}`,
      patientId,
      centreId: centreIdFor(patientId),
      sessionDate,
      arrivalWeightKg: arrival,
      postWeightKg: post,
      dryWeightKg: dry,
      durationMin: duration,
      systolicPre: systolic,
      diastolicPre: diastolic,
      systolicPost: null,
      diastolicPost: null,
      notes: notes ?? "",
      createdAt: `${sessionDate}T01:00:00.000Z`,
    }
  })

  const labs: BloodRecord[] = labSeeds.map((seed) => ({
    id: `lab-${seed.patientId}-${seed.takenOn}`,
    patientId: seed.patientId,
    takenOn: seed.takenOn,
    hemoglobin: seed.hemoglobin ?? null,
    ureaPre: seed.ureaPre ?? null,
    ureaPost: seed.ureaPost ?? null,
    creatinine: seed.creatinine ?? null,
    potassium: seed.potassium ?? null,
    phosphate: seed.phosphate ?? null,
    calcium: seed.calcium ?? null,
    sodium: seed.sodium ?? null,
    albumin: seed.albumin ?? null,
    notes: seed.notes ?? "",
    createdAt: `${seed.takenOn}T02:00:00.000Z`,
  }))

  return {
    centres: centres.map((centre) => ({ ...centre })),
    patients: patients.map((patient) => ({ ...patient })),
    sessions,
    labs,
  }
}
